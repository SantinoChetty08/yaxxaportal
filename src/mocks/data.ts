export const didsSeed: DidRecord[] = Array.from({ length: 34 }, (_, index) => {
  const provider = providers[index % providers.length];
  const assignedTenant = index < 24 ? tenantsSeed[index % tenantsSeed.length] : null;
  const tenantCampaigns = assignedTenant
    ? tenantCampaignsSeed.filter((campaign) => campaign.tenantId === assignedTenant.id && campaign.status === "active")
    : [];
  const assignedCampaign = tenantCampaigns[index % Math.max(tenantCampaigns.length, 1)] ?? null;

  let status: DidRecord["status"] = "free";
  if (assignedTenant) status = "active";
  if (!assignedTenant && index % 7 === 0) status = "reserved";
  if (!assignedTenant && index % 11 === 0) status = "quarantined";

  return {
    id: `DID-${index + 1}`,
    number: `${provider.prefix}${String(100000000 + index).slice(0, provider.prefix === "+254" ? 9 : 9)}`,
    provider: status === "free" && index % 9 === 0 ? null : provider.provider,
    trunk: status === "free" && index % 9 === 0 ? null : provider.trunk,
    tenantId: assignedTenant?.id ?? null,
    tenantName: assignedTenant?.name ?? null,
    campaignId: status === "active" ? assignedCampaign?.id ?? null : null,
    campaignName: status === "active" ? assignedCampaign?.name ?? null : null,
    status,
    country: provider.country,
    prefix: provider.prefix,
    createdAt: new Date(Date.parse("2025-01-01T00:00:00Z") + index * 86_400_000 * 8).toISOString(),
  };
});

tenantCampaignsSeed.forEach((campaign, index) => {
  const matchingDids = didsSeed
    .filter((did) => did.campaignId === campaign.id)
    .map((did) => did.id);
  campaign.didIds = matchingDids.length > 0 ? matchingDids : index % 4 === 0 ? [didsSeed[index % didsSeed.length].id] : [];
});

